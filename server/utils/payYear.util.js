const moment = require("moment");

// PAYYEAR-01: pay-period numbers restart every payroll year (period 1 of 2026
// ends 2025-12-28), so a processed pay stub is identified by its pay period AND
// its payroll year. The payroll year is the calendar year of payPeriodPayDate
// (CRA taxes income in the year it is paid; reportController.getReportInfo
// already windows report reads by pay-date year). Pay dates are compared in UTC,
// the form FundingTotalsPay (stream D) and pay stubs are stored in.

const toUtcMoment = (date) => {
	if (date === null || date === undefined || date === "") return null;
	const m = moment.utc(date);
	return m.isValid() ? m : null;
};

/** Pay date at UTC start of day (the stored form); invalid/missing values are returned as is. */
const normalisePayDate = (date) => {
	const m = toUtcMoment(date);
	return m ? m.startOf("day").toDate() : date;
};

/** Payroll year of a pay date, or null when there is no usable pay date. */
const payYearOf = (date) => toUtcMoment(date)?.year() ?? null;

/** Mongo range matching every pay date of a payroll year: [Jan 1, Jan 1 next) UTC. */
const payYearWindow = (year) => ({
	$gte: new Date(Date.UTC(year, 0, 1)),
	$lt: new Date(Date.UTC(year + 1, 0, 1)),
});

/** Year window of the given pay date, or null when there is no usable pay date. */
const payDateYearWindow = (date) => {
	const year = payYearOf(date);
	return year === null ? null : payYearWindow(year);
};

/** Mongo range matching one UTC day (old stubs may carry a time part). */
const payDateDayWindow = (date) => {
	const m = toUtcMoment(date);
	if (!m) return date;
	const start = m.startOf("day");
	return { $gte: start.toDate(), $lt: start.clone().add(1, "day").toDate() };
};

// Periods per year as generated by setUpController.addPaygroupSchedules (the
// numbering the pay runs use; taxService.FREQUENCY_MAP differs for Daily).
const PERIODS_PER_YEAR = {
	daily: 365,
	weekly: 52,
	biweekly: 26,
	"bi-weekly": 26,
	semimonthly: 24,
	monthly: 12,
	quarterly: 4,
	annually: 1,
};

/** Number of the last pay period of a year for a schedule frequency (26 when unknown, the old convention). */
const lastPayPeriodNum = (scheduleFrequency) =>
	PERIODS_PER_YEAR[String(scheduleFrequency || "").toLowerCase()] || 26;

/**
 * Year window of the most recent pay stub matching `filter` (fallback for readers
 * that have no pay date to scope by). Resolves to null when nothing matches.
 */
const latestPayYearWindow = async (Model, filter) => {
	const latest = await Model.findOne({ ...filter, payPeriodPayDate: { $ne: null } })
		.sort({ payPeriodPayDate: -1 })
		.select("payPeriodPayDate");
	return latest ? payDateYearWindow(latest.payPeriodPayDate) : null;
};

module.exports = {
	normalisePayDate,
	payYearOf,
	payYearWindow,
	payDateYearWindow,
	payDateDayWindow,
	lastPayPeriodNum,
	latestPayYearWindow,
	PERIODS_PER_YEAR,
};
